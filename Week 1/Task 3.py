# 1. Integer to Float
original_integer = 10
converted_float = float(original_integer)

print(converted_float)
print(type(converted_float))


# 2. Float to Integer
original_float = 10.5
converted_integer = int(original_float)

print(converted_integer)
print(type(converted_integer))


# 3. Integer to String
original_integer = 10
converted_string = str(original_integer)

print(converted_string)
print(type(converted_string))


# 4. String to Integer
original_string = "25"
converted_integer = int(original_string)

print(converted_integer)
print(type(converted_integer))


# 5. Integer to Boolean
original_integer = 1
converted_boolean = bool(original_integer)

print(converted_boolean)
print(type(converted_boolean))
